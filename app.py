# The page is designed for a light background only.
FORCE_LIGHT = "() => document.body.classList.remove('dark')"


def paragraphs(text):
    parts = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    return "".join(f"<p>{html.escape(p).replace(chr(10), '<br>')}</p>" for p in parts)


def render_transcript(turns, status=None, error=None):
    cards = []
    for t in turns:
        side = "gov" if t.side == "Government" else "opp"
        cards.append(
            f'<div class="turn {side}"><div class="meta"><span>{t.side}'
            f'<em class="mdl">{html.escape(t.model)}</em></span>'
            f'<span class="rd">Round {t.round} of {t.rounds}</span></div>{paragraphs(t.text)}</div>')
    if error:
        cards.append(f'<div class="turn err"><div class="meta"><span>Error</span></div>'
                     f'{paragraphs(error)}</div>')
    if status:
        cards.append(f'<div class="waiting">{html.escape(status)}'
                     '<span class="dots"><i></i><i></i><i></i></span></div>')
    if not cards:
        cards.append('<p class="empty">The transcript will appear here once the debate starts.</p>')
    return f'<div class="debate">{"".join(cards)}</div>'


def render_stats(stats=None, message=None):
    if message:
        return f'<div class="stats-note">{html.escape(message)}</div>'
    if stats is None or not stats.series:
        return ('<div class="stats-note">No World Bank data could be loaded: the country was not '
                'recognised or the API could not be reached. The models will rely on their own '
                'knowledge, so check any statistics they quote.</div>')
    rows = "".join(f"<tr><td>{html.escape(label)}</td><td>{html.escape(text)}</td></tr>"
                   for label, text in stats.rows())
    missing = ""
    if stats.missing:
        missing = ('<div class="stats-note">Not available for this country: '
                   + html.escape("; ".join(stats.missing)) + ".</div>")
    return (f'<div class="stats-title">{html.escape(stats.country)} &middot; World Bank Open Data'
            f'</div><table class="stats">{rows}</table>{missing}')


def start_debate(country, topic, rounds):
    country = (country or "").strip()
    if not country:
        raise gr.Error("Enter a country first.")
    try:
        client = debate.make_client()
    except RuntimeError as error:
        raise gr.Error(str(error))

    yield (render_transcript([], "Loading statistics from the World Bank"),
           render_stats(message="Loading statistics from the World Bank..."))
    stats = worldbank.fetch(country)
    stats_html = render_stats(stats)
    if stats is not None and not stats.series:
        stats = None

    turns = []
    try:
        for turns, status in debate.run(client, country, topic, rounds, stats):
            yield render_transcript(turns, status), stats_html
    except Exception as error:
        yield render_transcript(turns, error=str(error)), stats_html


with gr.Blocks(title="Government versus Opposition", theme=THEME, css=CSS,
               head=FONTS, js=FORCE_LIGHT) as demo:
    gr.HTML(MASTHEAD)
    with gr.Row():
        country_box = gr.Textbox(label="Country", placeholder="Egypt, Brazil, Germany")
        topic_box = gr.Textbox(label="Topic (optional)", placeholder="inflation, healthcare")
    rounds_box = gr.Radio(list(range(1, debate.MAX_ROUNDS + 1)), value=3,
                          label=f"Rounds (maximum {debate.MAX_ROUNDS})")
    start = gr.Button("Start debate", variant="primary")
    with gr.Accordion("Statistics given to both sides", open=False):
        stats_out = gr.HTML(render_stats(message="Statistics appear here once a debate starts."))
    transcript_out = gr.HTML(render_transcript([]))
    gr.HTML(FINEPRINT)

    start.click(start_debate, [country_box, topic_box, rounds_box], [transcript_out, stats_out])

if __name__ == "__main__":
    demo.launch()
